/// 把文本中的已知 emoji 按映射表转换为 `[表情名称]` 纯文本。
/// 已存在的 `[xxx]`、普通文字、标点、空格、换行不受影响；
/// 映射表之外的 emoji 原样保留（不丢字符）。
String emojiToShortcodes(String text) {
  if (text.isEmpty) return text;
  final buffer = StringBuffer();
  for (final grapheme in text.characters) {
    final code = emojiShortcodes[grapheme];
    buffer.write(code != null ? '[$code]' : grapheme);
  }
  return buffer.toString();
}
