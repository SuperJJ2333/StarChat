"""Isolated two-process ASGI calibration; no network, credentials or production data."""

import asyncio
import json
import math
import multiprocessing
import os
from pathlib import Path
import sys
import threading
import time

ROOT = Path(__file__).resolve().parents[5]
sys.path[:0] = [str(ROOT / "services/business-api"),
               str(ROOT / "tests/business_api/media_platform")]


def worker(index, destination, queue):
    import anyio
    from httpx import ASGITransport, AsyncClient
    from test_media_event_loop import media_io_env

    directory = Path(destination) / f"probe-worker-{index}-{os.getpid()}"
    directory.mkdir(exist_ok=True)
    fixture = media_io_env.__wrapped__(directory)
    env = next(fixture)
    app, _, _, avatar_url, _, _, transport, _ = env
    # 64 KiB opaque synthetic avatar object, valid S3 checksum generated by the
    # transport. This is a scheduler calibration, not an image-decoder test.
    for key in transport.objects:
        if key.startswith("business/avatars/"):
            transport.objects[key] = b"x" * 65536

    class SlowIO:
        def wait(self):
            threading.Event().wait(0.125)

    # S3 performs a body read and EOF read: 2 x 125 ms = 250 ms total per object.
    transport.gate = SlowIO()

    async def measure():
        limiter = anyio.to_thread.current_default_thread_limiter()
        lag_ms = []
        live_ms = []
        occupancy = []
        async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test") as client:
            responses = []
            done = asyncio.Event()

            async def media_load():
                try:
                    for _ in range(6):
                        responses.extend(await asyncio.gather(client.get(avatar_url), client.get(avatar_url)))
                finally:
                    done.set()

            async def timer():
                while not done.is_set():
                    due = time.perf_counter() + 0.01
                    # Windows' coarse monotonic clock can wake an asyncio timer
                    # early. Count only elapsed 10 ms intervals in perf_counter.
                    while (remaining := due - time.perf_counter()) > 0:
                        await asyncio.sleep(max(0.001, remaining))
                    lag_ms.append(max(0.0, (time.perf_counter() - due) * 1000))
                    occupancy.append(limiter.borrowed_tokens)

            async def light_load():
                while not done.is_set():
                    before = time.perf_counter()
                    assert (await client.get("/api/v1/health/live")).status_code == 200
                    live_ms.append((time.perf_counter() - before) * 1000)
                    await asyncio.sleep(0.01)

            started = time.perf_counter()
            await asyncio.gather(media_load(), timer(), light_load())
            assert all(response.status_code == 200 and len(response.content) == 65536
                       for response in responses)
            elapsed = time.perf_counter() - started

        def percentile(values, quantile):
            return sorted(values)[math.ceil(len(values) * quantile) - 1]

        return {"worker": index, "pid": os.getpid(), "requests": len(responses),
            "object_bytes": 65536, "storage_wait_ms": 250, "thread_tokens": limiter.total_tokens,
            "media_concurrency": 2,
            "max_borrowed_tokens": max(occupancy), "elapsed_seconds": elapsed,
            "samples": len(lag_ms), "loop_lag_p99_ms": percentile(lag_ms, .99),
            "loop_lag_max_ms": max(lag_ms), "live_p99_ms": percentile(live_ms, .99)}

    try:
        result = asyncio.run(measure())
        result["loop_lag_p99_under_50ms"] = result["loop_lag_p99_ms"] < 50
        try:
            import psutil
            memory = psutil.Process().memory_info()
            result["rss_bytes"] = memory.rss
            result["peak_rss_bytes"] = getattr(memory, "peak_wset", None)
        except ImportError:
            if sys.platform == "win32":
                import ctypes
                from ctypes import wintypes

                class Counters(ctypes.Structure):
                    _fields_ = [("cb", wintypes.DWORD), ("PageFaultCount", wintypes.DWORD),
                        ("PeakWorkingSetSize", ctypes.c_size_t), ("WorkingSetSize", ctypes.c_size_t),
                        ("QuotaPeakPagedPoolUsage", ctypes.c_size_t), ("QuotaPagedPoolUsage", ctypes.c_size_t),
                        ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t), ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
                        ("PagefileUsage", ctypes.c_size_t), ("PeakPagefileUsage", ctypes.c_size_t)]

                counters = Counters()
                counters.cb = ctypes.sizeof(counters)
                get_process = ctypes.windll.kernel32.GetCurrentProcess
                get_process.restype = wintypes.HANDLE
                memory_info = ctypes.windll.psapi.GetProcessMemoryInfo
                memory_info.argtypes = [wintypes.HANDLE, ctypes.POINTER(Counters), wintypes.DWORD]
                assert memory_info(get_process(), ctypes.byref(counters), counters.cb)
                result["rss_bytes"] = counters.WorkingSetSize
                result["peak_rss_bytes"] = counters.PeakWorkingSetSize
            else:
                result["peak_rss_bytes"] = None
        queue.put(result)
    finally:
        try:
            next(fixture)
        except StopIteration:
            pass


if __name__ == "__main__":
    destination = Path(__file__).resolve().parent
    context = multiprocessing.get_context("spawn")
    queue = context.Queue()
    workers = [context.Process(target=worker, args=(i, str(destination), queue)) for i in range(2)]
    for process in workers:
        process.start()
    for process in workers:
        process.join(timeout=60)
        assert process.exitcode == 0, f"worker exit {process.exitcode}"
    results = sorted([queue.get(timeout=5) for _ in workers], key=lambda value: value["worker"])
    payload = {"synthetic_only": True, "worker_count": 2, "results": results}
    (destination / "two-worker-probe.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(json.dumps(payload, indent=2))
